import { chromium } from "@playwright/test";
import { mkdir, rename, writeFile } from "node:fs/promises";
import { readFileSync } from "node:fs";
const deployment = JSON.parse(readFileSync("evidence/deployment.json", "utf8"));
await mkdir("evidence/demo", { recursive: true });
const browser = await chromium.launch({ channel: process.env.PW_CHANNEL ?? "msedge" });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, recordVideo: { dir: "evidence/demo", size: { width: 1280, height: 900 } } });
const page = await context.newPage();
page.setDefaultTimeout(30000);
page.on("console", message => console.log("browser: " + message.text().slice(0, 150)));
console.log("Opening application");
const video = page.video();
await page.goto(process.env.APP_URL ?? "http://127.0.0.1:4173");
await page.getByRole("heading", { name: "Usage is visible. Value capture still has to be proved." }).waitFor();
console.log("Evidence loaded");
await page.waitForTimeout(4000);
await page.getByRole("button", { name: "Scenario workbench" }).click();
await page.waitForTimeout(4000);
await page.getByLabel("Annual actual protocol burn").fill("30000000");
await page.waitForTimeout(4000);
await page.getByLabel("Inventory holding duration").fill("0.25");
await page.waitForTimeout(4000);
await page.getByRole("button", { name: "Historical comparison" }).click();
await page.waitForTimeout(4000);
await page.getByRole("button", { name: "Report & export" }).click();
await page.getByRole("button", { name: "Freeze current report" }).click();
const downloadPromise = page.waitForEvent("download");
await page.getByRole("button", { name: "Export reproducibility JSON" }).click();
const download = await downloadPromise;
console.log("Report exported");
await download.saveAs("evidence/demo/exported-research.json");
await page.waitForTimeout(4000);
await page.getByRole("button", { name: "Publication registry" }).click();
await page.getByLabel("Downloaded research bundle").setInputFiles("evidence/report.json");
await page.getByLabel("Publication ID", { exact: true }).fill(deployment.publications[0].publication_id);
await page.getByRole("button", { name: "Recompute & compare final state" }).click();
await page.getByText("Matching: downloaded bundle reproduces all three on-chain digests").waitFor({ timeout: 45000 });
console.log("Live testnet verification matched");
await page.waitForTimeout(7000);
const videoPath = await video.path();
await context.close(); await browser.close();
await rename(videoPath, "evidence/demo/research-workflow.webm");
await writeFile("evidence/demo/README.md", "# Recorded application walkthrough\n\nActual local application, real mainnet cached data, editable deterministic scenarios, report export, and a read-only verification against the deployed testnet registry. No mocked API/RPC/AI responses, no paid inference, and no wallet transaction are used in this recording. Pauses are automated for readability; the session is continuous. The exported bundle in this directory is a new local scenario and is not the already published original report used for verification.\n");
console.log("Recorded actual workflow and live read-only testnet verification.");
